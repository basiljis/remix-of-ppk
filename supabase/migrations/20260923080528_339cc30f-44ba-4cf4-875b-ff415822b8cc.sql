<h2>Что мы запускаем</h2>
<p>Специалисты, которые работают вне образовательной организации — в частной практике, в собственном кабинете, по совместительству — теперь получают <strong>полный доступ к платформе universum. на 12 месяцев бесплатно</strong>.</p>
<p>Доступ выдаётся <strong>автоматически при регистрации</strong>: не нужно подавать заявку, ждать одобрения или вводить платёжные данные.</p>
<h2>Кому это доступно</h2>
<ul>
<li>педагоги-психологи;</li>
<li>учителя-логопеды;</li>
<li>учителя-дефектологи;</li>
<li>другие специалисты помогающих профессий, ведущие частную практику.</li>
</ul>
<p><strong>Важно:</strong> бесплатный год не мешает работе в организации. Если вы одновременно сотрудничаете с образовательной организацией, вы можете пользоваться и личным бесплатным доступом, и доступом, который вам предоставит организация, — это разные учётные записи и разные пространства данных.</p>
<h2>Что входит в бесплатный год</h2>
<ul>
<li>карточка ребёнка как ядро системы: история развития, динамика, материалы;</li>
<li>диагностика и тесты с автоматическим подсчётом результатов;</li>
<li>планирование и учёт занятий, расписание;</li>
<li>рекомендации и материалы для родителей;</li>
<li>документы и выгрузки для отчётности.</li>
</ul>

<h2>1. Режим рабочего времени: 36 часов — как они делятся?</h2>
<p>Самый частый вопрос — как законно распределить 36 часов рабочей недели (для педагога-психолога). Согласно <strong>Приказу Минобрнауки № 536 (п. 8.1)</strong>:</p>
<ul class="list-disc pl-5 space-y-2">
  <li><strong>18 часов</strong> — «присутственные». Это непосредственная работа с участниками образовательного процесса: диагностика, коррекционно-развивающие занятия (групповые и инд.), консультирование.</li>
  <li><strong>18 часов</strong> — «методические». Подготовка к занятиям, обработка тестов, ведение журналов, самообразование, участие в педсоветах. Эти часы психолог может выполнять как в школе, так и за её пределами (если иное не прописано в локальном акте школы).</li>
</ul>
<p class="bg-yellow-50 p-3 text-sm rounded border border-yellow-200"><strong>Важно:</strong> Администрация не имеет права требовать нахождения на рабочем месте все 36 часов, если психолог выполнил свою «активную» часть нагрузки и занимается методической работой.</p>

